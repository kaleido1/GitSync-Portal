export function resolveLanguage(setting: LanguageSetting, systemLanguage = systemLocale()): ResolvedLanguage {
  if (setting !== "auto") return setting;
  const locale = systemLanguage.replace(/_/g, "-").toLocaleLowerCase();
  if (locale.startsWith("zh-tw") || locale.startsWith("zh-hk") || locale.startsWith("zh-mo") || locale.includes("hant")) return "zh-TW";
  if (locale.startsWith("zh")) return "zh";
  if (locale.startsWith("pt-br")) return "pt-BR";
  if (locale.startsWith("en-gb")) return "en-GB";
  for (const language of Object.keys(TRANSLATIONS) as ResolvedLanguage[]) {
    if (locale === language.toLocaleLowerCase() || locale.startsWith(`${language.toLocaleLowerCase()}-`)) return language;
  }
  return "en";
}

export function translate(setting: LanguageSetting, key: TranslationKey, values: Record<string, TranslationValue> = {}): string {
  const language = resolveLanguage(setting);
  const template = TRANSLATIONS[language][key] ?? EN[key];
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) => values[name] === undefined ? match : String(values[name]));
}

export function formatDateTime(setting: LanguageSetting, timestamp: number): string {
  return new Intl.DateTimeFormat(resolveLanguage(setting), { dateStyle: "medium", timeStyle: "short" }).format(new Date(timestamp));
}

function systemLocale(): string {
  try {
    const obsidianLanguage = globalThis.localStorage?.getItem("language")?.trim();
    if (obsidianLanguage) return obsidianLanguage;
  } catch {
    // localStorage can be unavailable in restricted test environments.
  }
  return typeof navigator === "undefined" ? "en" : navigator.language || "en";
}
